var MAX_RETRIES = 3;
var BASE_DELAY_MS = 1e3;
function sleep(ms) {
  return new Promise((resolve) => window.setTimeout(resolve, ms));
}
function shouldRetry(status) {
  return status === 429 || status >= 500;
}
async function putS3Object(config, key, body, contentType, formatError, precomputedHash) {
  const endpoint = String(config.endpoint || "").replace(/\/+$/, "");
  const bucket = config.bucketName;
  const encodedKey = key.split("/").map(encodeURIComponent).join("/");
  const url = `${endpoint}/${bucket}/${encodedKey}`;
  const parsed = new URL(url);
  const region = config.region || "auto";
  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    const now = /* @__PURE__ */ new Date();
    const amzDate = toAmzDate(now);
    const dateStamp = amzDate.slice(0, 8);
    const payloadHash = precomputedHash || await sha256Hex(body);
    const canonicalHeaders = [
      `host:${parsed.host}`,
      `x-amz-content-sha256:${payloadHash}`,
      `x-amz-date:${amzDate}`
    ].join("\n") + "\n";
    const signedHeaders = "host;x-amz-content-sha256;x-amz-date";
    const canonicalRequest = [
      "PUT",
      parsed.pathname,
      "",
      canonicalHeaders,
      signedHeaders,
      payloadHash
    ].join("\n");
    const credentialScope = `${dateStamp}/${region}/s3/aws4_request`;
    const canonicalRequestHash = await sha256Hex(new TextEncoder().encode(canonicalRequest));
    const stringToSign = [
      "AWS4-HMAC-SHA256",
      amzDate,
      credentialScope,
      canonicalRequestHash
    ].join("\n");
    const signingKey = await getSignatureKey(
      config.secretAccessKey,
      dateStamp,
      region,
      "s3"
    );
    const signature = await hmacSha256Hex(signingKey, stringToSign);
    const headers = {
      "Content-Type": contentType,
      "x-amz-content-sha256": payloadHash,
      "x-amz-date": amzDate,
      Authorization: `AWS4-HMAC-SHA256 Credential=${config.accessKeyId}/${credentialScope}, SignedHeaders=${signedHeaders}, Signature=${signature}`
    };
    try {
      const response = await (0, import_obsidian.requestUrl)({
        url,
        method: "PUT",
        headers,
        body: body.buffer.slice(body.byteOffset, body.byteOffset + body.byteLength),
        throw: false
      });
      if (response.status >= 200 && response.status < 300)
        return;
      if (shouldRetry(response.status) && attempt < MAX_RETRIES) {
        await sleep(BASE_DELAY_MS * Math.pow(2, attempt));
        continue;
      }
      throw new Error(formatError(response.status, response.text || ""));
    } catch (error) {
      if (error instanceof Error && error.message) {
        if (attempt >= MAX_RETRIES)
          throw error;
      }
      if (attempt < MAX_RETRIES) {
        await sleep(BASE_DELAY_MS * Math.pow(2, attempt));
        continue;
      }
      throw error;
    }
  }
}
