var emscriptenModule;
async function init(module2, moduleOptionOverrides) {
  let actualModule = module2;
  let actualOptions = moduleOptionOverrides;
  if (arguments.length === 1 && !(module2 instanceof WebAssembly.Module)) {
    actualModule = void 0;
    actualOptions = module2;
  }
  if (await simd()) {
    const webpEncoder2 = await Promise.resolve().then(() => (init_webp_enc_simd(), webp_enc_simd_exports));
    emscriptenModule = initEmscriptenModule(webpEncoder2.default, actualModule, actualOptions);
    return emscriptenModule;
  }
  const webpEncoder = await Promise.resolve().then(() => (init_webp_enc(), webp_enc_exports));
  emscriptenModule = initEmscriptenModule(webpEncoder.default, actualModule, actualOptions);
  return emscriptenModule;
}
async function encode(data, options = {}) {
  if (!emscriptenModule)
    emscriptenModule = init();
  const _options = { ...defaultOptions, ...options };
  const module2 = await emscriptenModule;
  const result = module2.encode(data.data, data.width, data.height, _options);
  if (!result)
    throw new Error("Encoding error.");
  return result.buffer;
}

// src/image-compressor.ts
var wasmInitialized = false;
function setWasmLoader(loader) {
  wasmLoader = loader;
}
var wasmLoader = null;
async function loadWasmModule(filename) {
  if (!wasmLoader)
    throw new Error("WASM loader not set");
  const buffer = await wasmLoader(filename);
  return WebAssembly.compile(buffer);
}
async function ensureWasmInit() {
  if (wasmInitialized)
    return;
  try {
    const wasmModule = await loadWasmModule("webp_enc.wasm");
    await init(wasmModule);
    wasmInitialized = true;
  } catch (e) {
    console.error("Failed to initialize WebP WASM encoder:", e);
    throw e;
  }
}
async function decodeImage(binary, ext) {
  const lowerExt = ext.toLowerCase();
  const blob = new Blob([binary], { type: mimeForExt(lowerExt) });
  const bitmap = await createImageBitmap(blob);
  const canvas = new OffscreenCanvas(bitmap.width, bitmap.height);
  const ctx = canvas.getContext("2d");
  if (!ctx)
    throw new Error("Failed to get OffscreenCanvas 2D context");
  ctx.drawImage(bitmap, 0, 0);
  const imageData = ctx.getImageData(0, 0, bitmap.width, bitmap.height);
  bitmap.close();
  return imageData;
}
function mimeForExt(ext) {
  const map = {
    png: "image/png",
    jpg: "image/jpeg",
    jpeg: "image/jpeg",
    bmp: "image/bmp",
    webp: "image/webp",
    tiff: "image/tiff",
    tif: "image/tiff",
    ico: "image/x-icon"
  };
  return map[ext] || "application/octet-stream";
}
async function compressToWebp(binary, ext, quality) {
  await ensureWasmInit();
  const imageData = await decodeImage(binary, ext);
  const options = { quality };
  const webpBuffer = await encode(imageData, options);
  const body = new Uint8Array(webpBuffer);
  return {
    body,
    ext: "webp",
    contentType: "image/webp",
    originalSize: binary.byteLength,
    compressedSize: body.byteLength
  };
}

